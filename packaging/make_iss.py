"""Write the Inno Setup script that builds RiffTag's Windows installer.

Generated rather than hand-written for the same reason the .desktop entries
are: the file-type list has to come from ``rifftag/desktopfile.py`` or it
drifts, and drift there is what left RiffTag out of the "Open with" menu for
.wav files on Linux. One list, four consumers.

Run it from the project root::

    python3 packaging/make_iss.py build/windows/rifftag.iss 0.3

Then compile with Inno Setup's command-line compiler, which is Windows only::

    "C:\\Program Files (x86)\\Inno Setup 6\\ISCC.exe" build\\windows\\rifftag.iss

``packaging/build_windows.bat`` (in the WinBoat shared folder) does both.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from rifftag.desktopfile import extensions  # noqa: E402

#: Never change this. It is the identity Windows stores for the installed
#: program: change it and an upgrade installs a second copy beside the first
#: instead of replacing it, and the old one's uninstaller is orphaned.
APP_ID = "{01FB28A0-3875-4216-8608-FA4ED33E7B54}"


def app_id_literal() -> str:
    """The AppId as Inno Setup needs it written: ``{{GUID}``.

    A single ``{`` opens a *constant* in an .iss file, so a raw ``{GUID}``
    is read as one and the compile dies with::

        Unknown constant "01FB28A0-3875-4216-8608-FA4ED33E7B54".

    Doubling only the opening brace is the documented escape, and is what
    Inno's own script wizard emits. The closing brace stays single.
    """
    return "{" + APP_ID

PROG_ID = "RiffTag.AudioFile"

#: Windows refuses to let an installer seize a default handler, and taking
#: the double-click away from someone's music player is not what installing a
#: tag editor means. The installer registers OpenWithProgids, exactly what
#: packaging/register-windows.ps1 does by hand, and leaves defaults alone.
_HEADER = '''\
; GENERATED by packaging/make_iss.py - do not edit by hand.
; The file-type list comes from rifftag/desktopfile.py, which is also where
; the Linux .desktop entries get theirs.

#define MyAppName "RiffTag"
#define MyAppPublisher "Dave Yeubanks"
#define MyAppURL "https://rifftag.nobody777.com"
#define MyAppExeName "RiffTag.exe"

[Setup]
AppId={APP_ID}
AppName={{#MyAppName}}
AppVersion={VERSION}
AppVerName={{#MyAppName}} {VERSION}
AppPublisher={{#MyAppPublisher}}
AppPublisherURL={{#MyAppURL}}
AppSupportURL=https://github.com/mynameisnobody777/rifftag/issues
AppUpdatesURL={{#MyAppURL}}
DefaultDirName={{autopf}}\\{{#MyAppName}}
DefaultGroupName={{#MyAppName}}
; Per-user by default, so there is no UAC prompt and no administrator needed
; - the same choice the HKCU file associations make. The dialog lets anyone
; who wants a machine-wide install have one.
PrivilegesRequired=lowest
PrivilegesRequiredOverridesAllowed=dialog
OutputDir={OUTPUT_DIR}
OutputBaseFilename=RiffTag-{VERSION}-Setup
SetupIconFile={ICON}
Compression=lzma2/max
SolidCompression=yes
WizardStyle=modern
LicenseFile={LICENSE}
UninstallDisplayName={{#MyAppName}} {VERSION}
UninstallDisplayIcon={{app}}\\{{#MyAppExeName}}
; x64compatible needs Inno Setup 6.3 or newer, and is the RIGHT identifier
; under 7, where plain x64 is deprecated and compiles with a warning. It
; matches x64 Windows and Arm64 Windows 11 both. On anything older than 6.3
; these two lines are the only thing that will refuse to compile.
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible

[Languages]
Name: "english"; MessagesFile: "compiler:Default.isl"

[Tasks]
Name: "desktopicon"; Description: "{{cm:CreateDesktopIcon}}"; \\
    GroupDescription: "{{cm:AdditionalIcons}}"; Flags: unchecked
Name: "associate"; \\
    Description: "Add RiffTag to the ""Open with"" menu for audio files"; \\
    GroupDescription: "File types:"

[Files]
; The whole PyInstaller folder. recursesubdirs because Qt's plugins live
; several levels down and a flat copy produces an exe that starts and then
; dies with "could not find or load the Qt platform plugin".
Source: "{DIST}\\*"; DestDir: "{{app}}"; \\
    Flags: ignoreversion recursesubdirs createallsubdirs

[Icons]
Name: "{{group}}\\{{#MyAppName}}"; Filename: "{{app}}\\{{#MyAppExeName}}"
Name: "{{group}}\\{{cm:UninstallProgram,{{#MyAppName}}}}"; \\
    Filename: "{{uninstallexe}}"
Name: "{{autodesktop}}\\{{#MyAppName}}"; \\
    Filename: "{{app}}\\{{#MyAppExeName}}"; Tasks: desktopicon

[Run]
Filename: "{{app}}\\{{#MyAppExeName}}"; \\
    Description: "{{cm:LaunchProgram,{{#MyAppName}}}}"; \\
    Flags: nowait postinstall skipifsilent
'''

_REGISTRY_HEAD = '''
[Registry]
; The ProgID: what the shell shows and what it runs. "%1" stays quoted -
; without the quotes a path with a space in it, which is most music, arrives
; as several arguments.
Root: HKA; Subkey: "Software\\Classes\\{PROG_ID}"; \\
    ValueType: string; ValueName: ""; ValueData: "Audio file"; \\
    Flags: uninsdeletekey; Tasks: associate
Root: HKA; Subkey: "Software\\Classes\\{PROG_ID}"; \\
    ValueType: string; ValueName: "FriendlyTypeName"; ValueData: "Audio file"; \\
    Tasks: associate
Root: HKA; Subkey: "Software\\Classes\\{PROG_ID}\\DefaultIcon"; \\
    ValueType: string; ValueName: ""; \\
    ValueData: "{{app}}\\{{#MyAppExeName}},0"; Tasks: associate
Root: HKA; Subkey: "Software\\Classes\\{PROG_ID}\\shell\\open\\command"; \\
    ValueType: string; ValueName: ""; \\
    ValueData: """{{app}}\\{{#MyAppExeName}}"" ""%1"""; Tasks: associate

; Applications\\RiffTag.exe is what makes the entry read "RiffTag" in the
; Open with list instead of the bare file name.
Root: HKA; Subkey: "Software\\Classes\\Applications\\{{#MyAppExeName}}"; \\
    ValueType: string; ValueName: "FriendlyAppName"; ValueData: "{{#MyAppName}}"; \\
    Flags: uninsdeletekey; Tasks: associate
Root: HKA; \\
    Subkey: "Software\\Classes\\Applications\\{{#MyAppExeName}}\\shell\\open\\command"; \\
    ValueType: string; ValueName: ""; \\
    ValueData: """{{app}}\\{{#MyAppExeName}}"" ""%1"""; Tasks: associate
'''


def _registry_for(ext: str) -> str:
    """One extension's OpenWithProgids value, plus SupportedTypes.

    ``uninsdeletevalue`` and not ``uninsdeletekey``: the key belongs to the
    file type, not to RiffTag, and other programs have their own values in
    it. Removing the key on uninstall would take theirs with it.
    """
    return (
        f'Root: HKA; Subkey: "Software\\Classes\\{ext}\\OpenWithProgids"; \\\n'
        f'    ValueType: string; ValueName: "{PROG_ID}"; ValueData: ""; \\\n'
        f'    Flags: uninsdeletevalue; Tasks: associate\n'
        f'Root: HKA; '
        f'Subkey: "Software\\Classes\\Applications\\{{#MyAppExeName}}\\SupportedTypes"; \\\n'
        f'    ValueType: string; ValueName: "{ext}"; ValueData: ""; \\\n'
        f'    Flags: uninsdeletevalue; Tasks: associate\n'
    )


def render(version: str, dist: str, output_dir: str, icon: str,
           license_file: str) -> str:
    """The complete .iss text."""
    head = _HEADER.format(APP_ID=app_id_literal(), VERSION=version, DIST=dist,
                          OUTPUT_DIR=output_dir, ICON=icon,
                          LICENSE=license_file)
    body = _REGISTRY_HEAD.format(PROG_ID=PROG_ID)
    body += "\n" + "".join(_registry_for(ext) for ext in extensions())
    return head + body


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(__doc__)
        return 2
    out = Path(argv[1])
    version = argv[2]
    root = Path(__file__).resolve().parents[1]
    # Defaults match what build_windows.bat produces in the VM; every one can
    # be overridden so the generator is testable off a Windows box.
    dist = argv[3] if len(argv) > 3 else r"C:\RiffTag\dist\windows\RiffTag"
    outdir = argv[4] if len(argv) > 4 else r"C:\RiffTag\dist"
    icon = argv[5] if len(argv) > 5 else r"C:\RiffTag\assets\rifftag.ico"
    lic = argv[6] if len(argv) > 6 else r"C:\RiffTag\LICENSE"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(version, dist, outdir, icon, lic), encoding="utf-8")
    print(f"wrote {out} ({len(extensions())} file types), version {version}")
    assert root.exists()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
